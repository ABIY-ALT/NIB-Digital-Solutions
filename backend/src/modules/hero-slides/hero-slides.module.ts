import { Module } from '@nestjs/common';
import { HeroSettingsService } from './application/hero-settings.js';
import { HeroSlideApprovalHandlers } from './application/hero-slide-approval.handlers.js';
import {
  CreateHeroSlideUseCase,
  DeleteHeroSlideUseCase,
  GetHeroSlideUseCase,
  ListActiveHeroSlidesUseCase,
  ListHeroSlidesUseCase,
  ListOrderedHeroSlidesUseCase,
  ReorderHeroSlidesUseCase,
  UpdateHeroSlideUseCase,
} from './application/hero-slide.use-cases.js';
import { HERO_SLIDE_REPOSITORY } from './domain/hero-slide.repository.js';
import { PrismaHeroSlideRepository } from './infrastructure/prisma-hero-slide.repository.js';
import {
  HeroSlidesController,
  PublicHeroController,
} from './presentation/hero-slides.controller.js';

/**
 * Homepage hero carousel (generated by the AppCore feature generator, then
 * extended): slides with uploaded images (marketplace media), display order,
 * active flag and optional text / call to action, plus the carousel settings.
 * Staff manage it under /hero-slides; the website reads GET /marketplace/hero.
 */
@Module({
  controllers: [HeroSlidesController, PublicHeroController],
  providers: [
    { provide: HERO_SLIDE_REPOSITORY, useClass: PrismaHeroSlideRepository },
    ListHeroSlidesUseCase,
    ListOrderedHeroSlidesUseCase,
    ListActiveHeroSlidesUseCase,
    GetHeroSlideUseCase,
    CreateHeroSlideUseCase,
    UpdateHeroSlideUseCase,
    DeleteHeroSlideUseCase,
    ReorderHeroSlidesUseCase,
    HeroSettingsService,
    HeroSlideApprovalHandlers,
  ],
})
export class HeroSlidesModule {}
