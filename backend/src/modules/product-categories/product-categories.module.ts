import { Module } from '@nestjs/common';
import { ProductCategoryApprovalHandlers } from './application/product-category-approval.handlers.js';
import {
  CreateProductCategoryUseCase,
  DeleteProductCategoryUseCase,
  GetProductCategoryUseCase,
  ListProductCategoriesUseCase,
  UpdateProductCategoryUseCase,
} from './application/product-category.use-cases.js';
import { PRODUCT_CATEGORY_REPOSITORY } from './domain/product-category.repository.js';
import { PrismaProductCategoryRepository } from './infrastructure/prisma-product-category.repository.js';
import { ProductCategoriesController } from './presentation/product-categories.controller.js';

/** Product categories (generated by the AppCore feature generator). */
@Module({
  controllers: [ProductCategoriesController],
  providers: [
    { provide: PRODUCT_CATEGORY_REPOSITORY, useClass: PrismaProductCategoryRepository },
    ListProductCategoriesUseCase,
    GetProductCategoryUseCase,
    CreateProductCategoryUseCase,
    UpdateProductCategoryUseCase,
    DeleteProductCategoryUseCase,
    ProductCategoryApprovalHandlers,
  ],
  // Read by the public marketplace catalog.
  exports: [PRODUCT_CATEGORY_REPOSITORY],
})
export class ProductCategoriesModule {}
