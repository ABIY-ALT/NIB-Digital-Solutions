import { Module } from '@nestjs/common';
import { ReferenceDataModule } from '../reference-data/reference-data.module.js';
import { DigitalProductApprovalHandlers } from './application/digital-product-approval.handlers.js';
import {
  CreateDigitalProductUseCase,
  DeleteDigitalProductUseCase,
  GetDigitalProductUseCase,
  ListDigitalProductsUseCase,
  UpdateDigitalProductUseCase,
} from './application/digital-product.use-cases.js';
import { DIGITAL_PRODUCT_REPOSITORY } from './domain/digital-product.repository.js';
import { PrismaDigitalProductRepository } from './infrastructure/prisma-digital-product.repository.js';
import { DigitalProductsController } from './presentation/digital-products.controller.js';

/** Digital products (generated by the AppCore feature generator). */
@Module({
  // Industries and business needs are reference-data lists (validated on save).
  imports: [ReferenceDataModule],
  controllers: [DigitalProductsController],
  providers: [
    { provide: DIGITAL_PRODUCT_REPOSITORY, useClass: PrismaDigitalProductRepository },
    ListDigitalProductsUseCase,
    GetDigitalProductUseCase,
    CreateDigitalProductUseCase,
    UpdateDigitalProductUseCase,
    DeleteDigitalProductUseCase,
    DigitalProductApprovalHandlers,
  ],
  // Read by the public marketplace catalog.
  exports: [DIGITAL_PRODUCT_REPOSITORY],
})
export class DigitalProductsModule {}
