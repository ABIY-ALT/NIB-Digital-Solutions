import { BaseEntity, type EntityMetadata } from '#core/domain/base.entity.js';
import { ValidationError, type FieldIssue } from '#core/domain/errors/app-error.js';
import {
  AVAILABILITIES,
  DEPLOYMENTS,
  HEX_COLOUR,
  isOneOf,
  PLATFORMS,
  PRODUCT_STATUSES,
  SLUG_PATTERN,
  SUPPORT_STATUSES,
  UPCOMING_AVAILABILITIES,
} from '#modules/marketplace/domain/marketplace.constants.js';

/** Lower-case form of a reference-data item code (e.g. "education", "sme-business"). */
const TAXONOMY_CODE = /^[a-z0-9][a-z0-9_.-]{0,63}$/;

/**
 * Rich page content (benefits, modules, screenshots, demo, FAQs, …). Its shape
 * is validated by the controller's contract schema; the entity bounds its size.
 */
export type ProductContent = Record<string, unknown>;

/** Approved internal documentation section (assistant knowledge, staff only). */
export interface DocSection {
  title: string;
  body: string;
}

export interface DigitalProductProps {
  slug: string;
  name: string;
  tagline: string | null;
  summary: string;
  overview: string | null;
  problem: string | null;
  categoryCode: string;
  status: string;
  availability: string;
  featured: boolean;
  customizable: boolean;
  icon: string | null;
  accent: string | null;
  industries: string[];
  needs: string[];
  deployment: string[];
  platforms: string[];
  keyFeatures: string[];
  content: ProductContent;
  documentation: DocSection[];
  /** Expected release (YYYY-MM-DD) of an upcoming product. */
  releaseDate: string | null;
  developerId: string | null;
  backupDeveloperId: string | null;
  thirdDeveloperId: string | null;
  supportStatus: string;
}

export interface DigitalProductInput {
  slug: string;
  name: string;
  tagline?: string | null;
  summary: string;
  overview?: string | null;
  problem?: string | null;
  categoryCode: string;
  status: string;
  availability: string;
  featured?: boolean;
  customizable?: boolean;
  icon?: string | null;
  accent?: string | null;
  industries?: string[];
  needs?: string[];
  deployment?: string[];
  platforms?: string[];
  keyFeatures?: string[];
  content?: ProductContent;
  documentation?: DocSection[];
  releaseDate?: string | null;
  developerId?: string | null;
  backupDeveloperId?: string | null;
  thirdDeveloperId?: string | null;
  supportStatus?: string;
}

const ISO_DAY = /^\d{4}-\d{2}-\d{2}$/;
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/** Largest serialized page content accepted (keeps rows and payloads bounded). */
const MAX_CONTENT_BYTES = 200_000;

/**
 * Digital product in the marketplace catalog. Generated by the AppCore feature
 * generator, extended with the catalog vocabularies and page content.
 */
export class DigitalProduct extends BaseEntity {
  private constructor(
    meta: EntityMetadata,
    private props: DigitalProductProps,
  ) {
    super(meta);
  }

  static create(input: DigitalProductInput, actorId: string | null): DigitalProduct {
    const entity = new DigitalProduct(
      BaseEntity.newMetadata(actorId),
      DigitalProduct.validate(input),
    );
    entity.addEvent('digital-product.created', { id: entity.id });
    return entity;
  }

  static reconstitute(meta: EntityMetadata, props: DigitalProductProps): DigitalProduct {
    return new DigitalProduct(meta, props);
  }

  /** Normalises input and enforces field rules; throws VALIDATION_FAILED. */
  static validate(input: DigitalProductInput): DigitalProductProps {
    const issues: FieldIssue[] = [];
    const text = (
      field: keyof DigitalProductInput,
      value: string | null | undefined,
      max: number,
      required = false,
    ) => {
      const v = (value ?? '').trim();
      if (required && !v) issues.push({ field, message: 'This field is required' });
      if (v.length > max) issues.push({ field, message: `At most ${max} characters` });
      return v;
    };
    const list = (
      field: keyof DigitalProductInput,
      values: string[] | undefined,
      allowed?: readonly string[],
      max = 20,
    ) => {
      const clean = [...new Set((values ?? []).map((v) => v.trim()).filter(Boolean))];
      if (clean.length > max) issues.push({ field, message: `At most ${max} entries` });
      if (allowed && clean.some((v) => !allowed.includes(v)))
        issues.push({ field, message: 'Contains an unknown value' });
      return clean;
    };

    const slug = text('slug', input.slug, 80, true);
    if (slug && !SLUG_PATTERN.test(slug))
      issues.push({ field: 'slug', message: 'Use lowercase letters, numbers and hyphens' });
    const name = text('name', input.name, 160, true);
    const tagline = text('tagline', input.tagline, 160);
    const summary = text('summary', input.summary, 300, true);
    const overview = text('overview', input.overview, 2000);
    const problem = text('problem', input.problem, 2000);
    const categoryCode = text('categoryCode', input.categoryCode, 60, true);
    const status = text('status', input.status, 20, true);
    if (status && !isOneOf(PRODUCT_STATUSES, status))
      issues.push({ field: 'status', message: 'Unknown status' });
    const availability = text('availability', input.availability, 20, true);
    if (availability && !isOneOf(AVAILABILITIES, availability))
      issues.push({ field: 'availability', message: 'Unknown availability' });
    const icon = text('icon', input.icon, 40);
    const accent = text('accent', input.accent, 7);
    if (accent && !HEX_COLOUR.test(accent))
      issues.push({ field: 'accent', message: 'Use a hex colour such as #8B4E20' });
    // Industries and needs are managed reference data: the use cases check that
    // the codes exist; the entity only normalises them (lower case) and checks the form.
    const taxonomy = (field: 'industries' | 'needs', values: string[] | undefined) => {
      const codes = list(
        field,
        values?.map((v) => v.trim().toLowerCase()),
      );
      if (codes.some((c) => !TAXONOMY_CODE.test(c)))
        issues.push({ field, message: 'Contains an invalid code' });
      return codes;
    };
    const industries = taxonomy('industries', input.industries);
    const needs = taxonomy('needs', input.needs);
    const deployment = list('deployment', input.deployment, DEPLOYMENTS);
    const platforms = list('platforms', input.platforms, PLATFORMS);
    const keyFeatures = list('keyFeatures', input.keyFeatures, undefined, 6);
    if (keyFeatures.some((f) => f.length > 120))
      issues.push({ field: 'keyFeatures', message: 'Key features are at most 120 characters' });
    if (status === 'published') {
      if (!industries.length)
        issues.push({
          field: 'industries',
          message: 'Published products need at least one industry',
        });
      if (!keyFeatures.length)
        issues.push({
          field: 'keyFeatures',
          message: 'Published products need at least one key feature',
        });
    }
    const content = input.content ?? {};
    const documentation = (input.documentation ?? [])
      .map((d) => ({ title: d.title.trim(), body: d.body.trim() }))
      .filter((d) => d.title || d.body);
    if (JSON.stringify(content).length + JSON.stringify(documentation).length > MAX_CONTENT_BYTES) {
      issues.push({ field: 'content', message: 'Page content is too large' });
    }
    // Launch planning and developer support.
    const releaseDate = (input.releaseDate ?? '').trim();
    if (
      releaseDate &&
      (!ISO_DAY.test(releaseDate) || Number.isNaN(Date.parse(`${releaseDate}T00:00:00Z`)))
    )
      issues.push({ field: 'releaseDate', message: 'Use a date such as 2027-03-31' });
    const developerId = (input.developerId ?? '').trim();
    const backupDeveloperId = (input.backupDeveloperId ?? '').trim();
    if (developerId && !UUID.test(developerId))
      issues.push({ field: 'developerId', message: 'Choose a developer from the list' });
    if (backupDeveloperId && !UUID.test(backupDeveloperId))
      issues.push({ field: 'backupDeveloperId', message: 'Choose a developer from the list' });
    if (backupDeveloperId && backupDeveloperId === developerId)
      issues.push({
        field: 'backupDeveloperId',
        message: 'Choose a different developer as backup',
      });
    if (backupDeveloperId && !developerId)
      issues.push({ field: 'developerId', message: 'Choose the main developer first' });
    const thirdDeveloperId = (input.thirdDeveloperId ?? '').trim();
    if (thirdDeveloperId && !UUID.test(thirdDeveloperId))
      issues.push({ field: 'thirdDeveloperId', message: 'Choose a developer from the list' });
    if (
      thirdDeveloperId &&
      (thirdDeveloperId === developerId || thirdDeveloperId === backupDeveloperId)
    )
      issues.push({
        field: 'thirdDeveloperId',
        message: 'Choose a developer who is not already assigned',
      });
    if (thirdDeveloperId && !backupDeveloperId)
      issues.push({ field: 'backupDeveloperId', message: 'Choose the second developer first' });
    const supportStatus = (input.supportStatus ?? 'active').trim();
    if (!isOneOf(SUPPORT_STATUSES, supportStatus))
      issues.push({ field: 'supportStatus', message: 'Unknown support status' });
    if (issues.length) throw new ValidationError(issues);
    return {
      slug,
      name,
      tagline: tagline || null,
      summary,
      overview: overview || null,
      problem: problem || null,
      categoryCode,
      status,
      availability,
      featured: input.featured ?? false,
      customizable: input.customizable ?? false,
      icon: icon || null,
      accent: accent || null,
      industries,
      needs,
      deployment,
      platforms,
      keyFeatures,
      content,
      documentation,
      releaseDate: releaseDate || null,
      developerId: developerId || null,
      backupDeveloperId: backupDeveloperId || null,
      thirdDeveloperId: thirdDeveloperId || null,
      supportStatus,
    };
  }

  get releaseDate(): string | null {
    return this.props.releaseDate;
  }
  get developerId(): string | null {
    return this.props.developerId;
  }
  get backupDeveloperId(): string | null {
    return this.props.backupDeveloperId;
  }
  get thirdDeveloperId(): string | null {
    return this.props.thirdDeveloperId;
  }
  /** Every developer assigned to the product (1 to 3), main developer first. */
  get developerIds(): string[] {
    return [
      this.props.developerId,
      this.props.backupDeveloperId,
      this.props.thirdDeveloperId,
    ].filter((id): id is string => !!id);
  }
  get supportStatus(): string {
    return this.props.supportStatus;
  }
  /** Not launched yet (coming soon / in development). */
  get upcoming(): boolean {
    return isOneOf(UPCOMING_AVAILABILITIES, this.props.availability);
  }

  get slug(): string {
    return this.props.slug;
  }
  get name(): string {
    return this.props.name;
  }
  get tagline(): string | null {
    return this.props.tagline;
  }
  get summary(): string {
    return this.props.summary;
  }
  get overview(): string | null {
    return this.props.overview;
  }
  get problem(): string | null {
    return this.props.problem;
  }
  get categoryCode(): string {
    return this.props.categoryCode;
  }
  get status(): string {
    return this.props.status;
  }
  get availability(): string {
    return this.props.availability;
  }
  get featured(): boolean {
    return this.props.featured;
  }
  get customizable(): boolean {
    return this.props.customizable;
  }
  get icon(): string | null {
    return this.props.icon;
  }
  get accent(): string | null {
    return this.props.accent;
  }
  get industries(): string[] {
    return [...this.props.industries];
  }
  get needs(): string[] {
    return [...this.props.needs];
  }
  get deployment(): string[] {
    return [...this.props.deployment];
  }
  get platforms(): string[] {
    return [...this.props.platforms];
  }
  get keyFeatures(): string[] {
    return [...this.props.keyFeatures];
  }
  get content(): ProductContent {
    return this.props.content;
  }
  get documentation(): DocSection[] {
    return this.props.documentation.map((d) => ({ ...d }));
  }
  get isPublished(): boolean {
    return this.props.status === 'published';
  }

  update(changes: Partial<DigitalProductInput>, actorId: string | null): void {
    const defined = Object.fromEntries(Object.entries(changes).filter(([, v]) => v !== undefined));
    this.props = DigitalProduct.validate({ ...this.props, ...defined });
    this.touch(actorId);
  }

  toSnapshot(): Readonly<DigitalProductProps> {
    return { ...this.props };
  }
}
