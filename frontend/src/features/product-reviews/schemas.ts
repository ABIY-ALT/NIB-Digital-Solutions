import { z } from 'zod';
import type { ProductReview, ProductReviewInput } from './types';

type T = (key: string) => string;
const id: T = (k) => k;

/** pending: new, not shown · approved: on the website · rejected: never shown. */
export const REVIEW_STATUSES = ['pending', 'approved', 'rejected'] as const;
export type ReviewStatus = (typeof REVIEW_STATUSES)[number];
export const RATINGS = ['5', '4', '3', '2', '1'] as const;

/** Form schema (strings for inputs; converted by `toProductReviewInput`). */
export const productReviewFormSchema = (t: T = id) =>
  z.object({
    productSlug: z.string().trim().min(1, t('validation.required')).max(160),
    rating: z.enum(RATINGS, { message: t('validation.required') }),
    title: z.string().trim().max(160),
    body: z.string().trim().min(1, t('validation.required')).max(2000),
    reviewerName: z.string().trim().min(1, t('validation.required')).max(160),
    reviewerRole: z.string().trim().max(160),
    reviewerEmail: z.string().trim().email(t('validation.email')).max(160),
    status: z.enum(REVIEW_STATUSES, { message: t('validation.required') }),
    reply: z.string().trim().max(2000),
  });
export type ProductReviewFormValues = z.infer<ReturnType<typeof productReviewFormSchema>>;

export const productReviewFormDefaults = (e?: ProductReview | null): ProductReviewFormValues => ({
  productSlug: e?.productSlug ?? '',
  rating: (e ? String(e.rating) : '5') as ProductReviewFormValues['rating'],
  title: e?.title ?? '',
  body: e?.body ?? '',
  reviewerName: e?.reviewerName ?? '',
  reviewerRole: e?.reviewerRole ?? '',
  reviewerEmail: e?.reviewerEmail ?? '',
  // A review staff record themselves (e.g. from a meeting) is usually ready to publish.
  status: ((REVIEW_STATUSES as readonly string[]).includes(e?.status ?? '')
    ? e!.status
    : e
      ? 'pending'
      : 'approved') as ReviewStatus,
  reply: e?.reply ?? '',
});

/** The reference is generated by the server and never edited. */
export const toProductReviewInput = (v: ProductReviewFormValues): ProductReviewInput => ({
  productSlug: v.productSlug,
  rating: Number(v.rating),
  title: v.title || null,
  body: v.body,
  reviewerName: v.reviewerName,
  reviewerRole: v.reviewerRole || null,
  reviewerEmail: v.reviewerEmail.toLowerCase(),
  status: v.status,
  reply: v.reply || null,
});
